/**
 * Minimal AVM1 interpreter that can execute compiled achievement function bodies.
 * Supports the subset of opcodes generated by NativeEvalCompiler.
 */
class MiniAVM1 {
    private registers: unknown[] = new Array(16).fill(undefined);
    private stack: unknown[] = [];
    private data: Uint8Array;
    private pc = 0;

    constructor(
        functionBody: Uint8Array,
        gameRoot: Record<string, unknown>,
        storage: Record<string, unknown>,
    ) {
        this.data = functionBody;
        this.registers[1] = gameRoot; // R_GAMEROOT
        this.registers[2] = storage;  // R_STORAGE
    }

    execute(): unknown {
        while (this.pc < this.data.length) {
            const opcode = this.data[this.pc++];
            switch (opcode) {
                case 0x00: return 0; // ActionEnd
                case 0x96: this.opPush(); break;
                case 0x17: this.stack.pop(); break; // Pop
                case 0x4E: this.opGetMember(); break;
                case 0x4F: this.opSetMember(); break;
                case 0x87: this.opStoreRegister(); break;
                case 0x47: this.opAdd2(); break;
                case 0x0B: this.opSubtract(); break;
                case 0x0C: this.opMultiply(); break;
                case 0x0D: this.opDivide(); break;
                case 0x49: this.opEquals2(); break;
                case 0x48: this.opLess2(); break;
                case 0x67: this.opGreater(); break;
                case 0x12: this.opNot(); break;
                case 0x50: this.opIncrement(); break;
                case 0x51: this.opDecrement(); break;
                case 0x18: this.opToInteger(); break;
                case 0x4A: this.opToNumber(); break;
                case 0x62: this.opBitXor(); break;
                case 0x99: this.opJump(); break;
                case 0x9D: this.opJumpIf(); break;
                case 0x3E: return this.opReturn(); // Return
                case 0x1C: this.opGetVariable(); break;
                case 0x52: this.opCallMethod(); break;
                case 0x42: this.opInitArray(); break;
                case 0x54: this.opInstanceOf(); break;
                case 0x55: this.opEnumerate2(); break;
                case 0x8E: this.opDefineFunction2(); break;
                default:
                    throw new Error(`Unknown opcode 0x${opcode.toString(16)} at pc=${this.pc - 1}`);
            }
        }
        return 0;
    }

    private readUI16(): number {
        const lo = this.data[this.pc++];
        const hi = this.data[this.pc++];
        return lo | (hi << 8);
    }

    private readSI16(): number {
        const val = this.readUI16();
        return val >= 0x8000 ? val - 0x10000 : val;
    }

    private push(v: unknown): void { this.stack.push(v); }
    private pop(): unknown { return this.stack.pop(); }

    private toBoolean(v: unknown): boolean {
        if (v === undefined || v === null) return false;
        if (typeof v === "boolean") return v;
        if (typeof v === "number") return v !== 0 && !isNaN(v);
        if (typeof v === "string") return v.length > 0;
        return true;
    }

    private toNumber(v: unknown): number {
        if (v === undefined || v === null) return 0;
        if (typeof v === "number") return v;
        if (typeof v === "boolean") return v ? 1 : 0;
        if (typeof v === "string") return Number(v) || 0;
        return 0;
    }

    private opPush(): void {
        const dataLen = this.readUI16();
        const end = this.pc + dataLen;
        while (this.pc < end) {
            const type = this.data[this.pc++];
            switch (type) {
                case 0x00: { // string
                    let s = "";
                    while (this.pc < end && this.data[this.pc] !== 0) {
                        s += String.fromCharCode(this.data[this.pc++]);
                    }
                    this.pc++; // null terminator
                    this.push(s);
                    break;
                }
                case 0x02: this.push(null); break; // null
                case 0x03: this.push(undefined); break; // undefined
                case 0x04: this.push(this.registers[this.data[this.pc++]]); break; // register
                case 0x05: this.push(this.data[this.pc++] !== 0); break; // boolean
                case 0x06: { // double (SWF byte-swapped)
                    const buf = new ArrayBuffer(8);
                    const view = new DataView(buf);
                    // SWF stores high 4 bytes first, then low 4 bytes
                    for (let i = 4; i < 8; i++) view.setUint8(i, this.data[this.pc++]);
                    for (let i = 0; i < 4; i++) view.setUint8(i, this.data[this.pc++]);
                    this.push(view.getFloat64(0, true));
                    break;
                }
                case 0x07: { // integer
                    const b0 = this.data[this.pc++];
                    const b1 = this.data[this.pc++];
                    const b2 = this.data[this.pc++];
                    const b3 = this.data[this.pc++];
                    const val = b0 | (b1 << 8) | (b2 << 16) | (b3 << 24);
                    this.push(val);
                    break;
                }
                default:
                    throw new Error(`Unknown push type 0x${type.toString(16)}`);
            }
        }
    }

    private opGetMember(): void {
        const name = this.pop();
        const obj = this.pop() as Record<string, unknown>;
        if (obj === null || obj === undefined) {
            this.push(undefined);
        } else {
            this.push((obj as Record<string, unknown>)[String(name)]);
        }
    }

    private opSetMember(): void {
        const value = this.pop();
        const name = this.pop();
        const obj = this.pop() as Record<string, unknown>;
        if (obj !== null && obj !== undefined) {
            (obj as Record<string, unknown>)[String(name)] = value;
        }
    }

    private opStoreRegister(): void {
        const len = this.readUI16(); // always 1
        const reg = this.data[this.pc++];
        if (len !== 1) throw new Error("StoreRegister length != 1");
        this.registers[reg] = this.stack[this.stack.length - 1]; // peek
    }

    private opAdd2(): void {
        const b = this.pop();
        const a = this.pop();
        // AVM1 add2: string concatenation if either operand is a string, otherwise numeric
        if (typeof a === "string" || typeof b === "string") {
            this.push(String(a) + String(b));
        } else {
            this.push(this.toNumber(a) + this.toNumber(b));
        }
    }

    private opSubtract(): void {
        const b = this.pop();
        const a = this.pop();
        this.push(this.toNumber(a) - this.toNumber(b));
    }

    private opMultiply(): void {
        const b = this.pop();
        const a = this.pop();
        this.push(this.toNumber(a) * this.toNumber(b));
    }

    private opDivide(): void {
        const b = this.pop();
        const a = this.pop();
        this.push(this.toNumber(a) / this.toNumber(b));
    }

    private opEquals2(): void {
        const b = this.pop();
        const a = this.pop();
        // AVM1 equals2 uses loose equality
        this.push(a == b);
    }

    private opLess2(): void {
        const b = this.pop();
        const a = this.pop();
        this.push(this.toNumber(a) < this.toNumber(b));
    }

    private opGreater(): void {
        const b = this.pop();
        const a = this.pop();
        this.push(this.toNumber(a) > this.toNumber(b));
    }

    private opNot(): void {
        const v = this.pop();
        this.push(!this.toBoolean(v));
    }

    private opIncrement(): void {
        const v = this.pop();
        this.push(this.toNumber(v) + 1);
    }

    private opDecrement(): void {
        const v = this.pop();
        this.push(this.toNumber(v) - 1);
    }

    private opToInteger(): void {
        const v = this.pop();
        this.push(Math.trunc(this.toNumber(v)));
    }

    private opToNumber(): void {
        const v = this.pop();
        this.push(this.toNumber(v));
    }

    private opBitXor(): void {
        const b = this.pop();
        const a = this.pop();
        this.push(this.toNumber(a) ^ this.toNumber(b));
    }

    private opJump(): void {
        const _len = this.readUI16(); // data length (always 2)
        const offset = this.readSI16();
        // offset is relative to instruction end (which is current pc)
        // But we already consumed the length and offset fields via readUI16+readSI16
        // Actually: jumpTo calculates offset = target - (instrStart + 5)
        // At execution: the instruction is opcode(1) + len(2) + offset(2) = 5 bytes
        // After reading, pc points past the offset field, so pc is at instrStart + 5
        // So target = pc + offset
        // Wait, readUI16 already consumed len, then readSI16 consumed offset
        // pc is now at instrStart + 1 + 2 + 2 = instrStart + 5
        // The builder calculates: offset = target - (instrStart + 5)
        // So target = (instrStart + 5) + offset = this.pc + offset
        // But wait, pc was already advanced past the offset field
        // Actually let me re-think. After opcode (1 byte), we called readUI16 (2 bytes for data length),
        // then readSI16 (2 bytes for offset). So pc = start + 5. The builder sets
        // offset = targetPosition - (instrStart + 5). So targetPosition = pc + offset.
        // But actually: this.pc at the start of opJump was instrStart + 1 (after opcode read).
        // readUI16 advances by 2 → pc = instrStart + 3
        // readSI16 calls readUI16 which advances by 2 → pc = instrStart + 5
        // offset was calculated as target - (instrStart + 5) = target - this.pc
        // So target = this.pc + offset ← but this.pc is already instrStart + 5
        // Hmm wait, the _len read consumed 2 bytes, then the offset read consumed 2 bytes.
        // this.pc is now at instrStart + 1(opcode was consumed in main loop) + 2(len) + 2(offset) = instrStart + 5.
        // No wait, the main loop already consumed the opcode byte, so pc entered opJump at instrStart + 1.
        // Then readUI16 → pc = instrStart + 3. Then readSI16 → pc = instrStart + 5.
        // The builder's offset = target - (instrStart + 5). So target = offset + instrStart + 5 = offset + pc.
        // Hmm but pc = instrStart + 5 only if instrStart includes the opcode. Let me be precise.
        //
        // In the main loop: this.pc points at opcode, then this.pc++ reads it → pc is now at opcode + 1.
        // In opJump: readUI16 reads 2 bytes → pc at opcode + 3. readSI16 reads 2 bytes → pc at opcode + 5.
        // Builder: offset = targetPosition - (instrStart + 5), where instrStart = opcode position.
        // So targetPosition = offset + opcode_position + 5 = offset + this.pc (since this.pc = opcode + 5).
        this.pc = this.pc + offset;
    }

    private opJumpIf(): void {
        const _len = this.readUI16();
        const offset = this.readSI16();
        const cond = this.pop();
        if (this.toBoolean(cond)) {
            this.pc = this.pc + offset;
        }
    }

    private opReturn(): unknown {
        return this.pop();
    }

    private opGetVariable(): void {
        const name = this.pop() as string;
        if (name === "_global") {
            // Return a proxy that has __nativeAch
            this.push({ __nativeAch: [] });
        } else if (name === "Math") {
            this.push(Math);
        } else if (name === "Array") {
            this.push(Array);
        } else {
            this.push(undefined);
        }
    }

    private opInstanceOf(): void {
        const constructor = this.pop() as Function;
        const obj = this.pop();
        this.push(obj instanceof constructor);
    }

    private opCallMethod(): void {
        const methodName = this.pop() as string;
        const obj = this.pop() as Record<string, unknown>;
        const numArgs = this.toNumber(this.pop());
        const args: unknown[] = [];
        for (let i = 0; i < numArgs; i++) args.push(this.pop());
        if (obj && typeof (obj as Record<string, Function>)[methodName] === "function") {
            this.push((obj as Record<string, Function>)[methodName](...args));
        } else {
            this.push(undefined);
        }
    }

    private opInitArray(): void {
        const count = this.toNumber(this.pop());
        const arr: unknown[] = [];
        for (let i = 0; i < count; i++) arr.push(this.pop());
        this.push(arr);
    }

    private opEnumerate2(): void {
        const obj = this.pop() as Record<string, unknown>;
        // Push null sentinel, then push all property names
        this.push(null);
        if (obj !== null && obj !== undefined && typeof obj === "object") {
            for (const key of Object.keys(obj)) {
                this.push(key);
            }
        }
    }

    private opDefineFunction2(): void {
        const metaLen = this.readUI16();
        const metaStart = this.pc;
        // Skip name (null-terminated)
        while (this.data[this.pc++] !== 0);
        const numParams = this.readUI16();
        const _registerCount = this.data[this.pc++];
        const _flags = this.readUI16();
        // Skip params
        for (let i = 0; i < numParams; i++) {
            this.pc++; // register
            while (this.data[this.pc++] !== 0); // name
        }
        const codeSize = this.readUI16();
        // Verify we consumed all metadata
        if (this.pc !== metaStart + metaLen) {
            this.pc = metaStart + metaLen; // fix up
        }
        const bodyStart = this.pc;
        this.pc += codeSize; // skip over function body
        // Push a callable that creates a new VM for the function body
        const body = this.data.slice(bodyStart, bodyStart + codeSize);
        const fn = (gameRoot: Record<string, unknown>, storage: Record<string, unknown>): unknown => {
            const vm = new MiniAVM1(body, gameRoot, storage);
            return vm.execute();
        };
        this.push(fn);
    }
}

