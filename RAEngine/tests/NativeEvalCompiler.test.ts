/**
 * NativeEvalCompiler Tests
 *
 * Verifies that achievements compiled to native AVM1 bytecode produce identical
 * behavior to the interpreter. Uses a mini AVM1 virtual machine to execute the
 * compiled function bodies directly.
 *
 * Test coverage:
 *   - Simple comparisons (all 6 operators)
 *   - Hit tracking (increment, cap, locked-true)
 *   - Delta values (first frame init, subsequent frames)
 *   - PAUSE_IF (transient, threshold, chained)
 *   - RESET_IF (transient, threshold)
 *   - RESET_NEXT_IF
 *   - AND_NEXT / OR_NEXT chains
 *   - ADD_HITS / SUB_HITS chains
 *   - ADD_SOURCE / SUB_SOURCE
 *   - MEASURED (hit-count mode, value mode)
 *   - MEASURED_IF
 *   - TRIGGER / primed state
 *   - Multiple groups (CORE + ALT)
 *   - REMEMBER (cached values)
 *   - Arithmetic in formulas
 *   - Edge cases (empty results, boundary values)
 */

